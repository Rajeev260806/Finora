from __future__ import annotations

import os
import numpy as np
import pandas as pd
from gymnasium import spaces

from src.environment.portfolioenv import PortfolioEnv


class GNNPortfolioEnv(PortfolioEnv):
    """
    GNN-Enhanced Portfolio Environment for Phase 4 RL Training.
    Consumes real 32-dimensional node embeddings generated by Person A's proxy GNN.
    Supports modular risk-adjusted rewards, turnover transaction costs, and temporal date alignment.
    """

    def __init__(
        self,
        data: pd.DataFrame,
        embedding_dir: str | None = None,
        window: int = 20,
        transaction_cost_bps: float = 10.0,
        initial_cash: float = 1.0,
        return_col: str | None = None,
        embedding_dim: int = 32,
        lambda_vol: float = 0.10,
        lambda_conc: float = 0.01,
        lambda_txn: float = 1.0,
        residual_alpha: float = 0.0,
        seed: int | None = None,
    ):
        if embedding_dir is None:
            # Auto-detect default embeddings directory
            base_cand = os.path.join(
                os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))),
                "src",
                "gnn",
                "embeddings",
            )
            embedding_dir = base_cand if os.path.exists(base_cand) else os.path.join("src", "gnn", "embeddings")

        super().__init__(
            data=data,
            window=window,
            transaction_cost_bps=transaction_cost_bps,
            initial_cash=initial_cash,
            return_col=return_col,
            use_embeddings=True,
            embedding_dim=embedding_dim,
            embedding_dir=embedding_dir,
            lambda_vol=lambda_vol,
            lambda_conc=lambda_conc,
            lambda_txn=lambda_txn,
            residual_alpha=residual_alpha,
            seed=seed,
        )

        # Ensure observation space accurately reflects GNN embeddings
        self.observation_space = spaces.Dict(
            {
                "gnn_embeddings": spaces.Box(
                    low=-np.inf,
                    high=np.inf,
                    shape=(self.n_assets, self.embedding_dim),
                    dtype=np.float32,
                ),
                "weights": spaces.Box(
                    low=0.0,
                    high=1.0,
                    shape=(self.n_assets + 1,),
                    dtype=np.float32,
                ),
            }
        )

    def _load_embedding(self, idx: int) -> np.ndarray:
        return self._load_or_generate_embeddings(idx)

    def _get_observation(self, idx: int) -> dict:
        return {
            "gnn_embeddings": self._load_embedding(idx),
            "weights": self.prev_weights.copy(),
        }