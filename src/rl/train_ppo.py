"""
Finora Phase 4 (Person B) — PPO Training on GNN-Enhanced Environment
===================================================================
Trains a PPO agent (Stable-Baselines3) using real 32-dimensional GNN node
embeddings generated by Person A's proxy GNN.

Features:
- Dual logging: TensorBoard (results/ppo_logs/) and CSV monitoring
- Periodic checkpoint saving to results/ppo_checkpoints/
- Modular Phase 2 reward formulation:
  R_t = ln(1 + r_port,t - lambda_txn * c_t) - lambda_vol * sigma_20,t^ann - lambda_conc * HHI_t
- Saves final trained model to results/ppo_final_model.zip
"""

from __future__ import annotations

import os
import sys
import argparse
import numpy as np
import pandas as pd

# Add workspace root to sys.path
BASE_DIR = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, BASE_DIR)

from stable_baselines3 import PPO
from stable_baselines3.common.callbacks import CheckpointCallback, CallbackList, BaseCallback
from stable_baselines3.common.monitor import Monitor
from stable_baselines3.common.env_checker import check_env

from src.environment.gnn_portfolio_env import GNNPortfolioEnv


class MetricsLoggerCallback(BaseCallback):
    """Logs episode metrics to a CSV file for tracking training dynamics."""

    def __init__(self, log_path: str, verbose: int = 0):
        super().__init__(verbose)
        self.log_path = log_path
        self.records: list[dict] = []
        os.makedirs(os.path.dirname(log_path), exist_ok=True)

    def _on_step(self) -> bool:
        infos = self.locals.get("infos", [])
        for info in infos:
            if "episode" in info:
                ep_reward = info["episode"]["r"]
                ep_length = info["episode"]["l"]
                self.records.append({
                    "timestep": self.num_timesteps,
                    "episode_reward": ep_reward,
                    "episode_length": ep_length,
                })
        return True

    def _on_training_end(self) -> None:
        if self.records:
            df = pd.DataFrame(self.records)
            df.to_csv(self.log_path, index=False)
            print(f"[Logger] Episode history saved to: {self.log_path}")


def train_ppo(
    data_path: str = "data/clean/train.parquet",
    embedding_dir: str = "src/gnn/embeddings",
    total_timesteps: int = 100000,
    save_freq: int = 25000,
    learning_rate: float = 3e-4,
    n_steps: int = 2048,
    batch_size: int = 64,
    n_epochs: int = 10,
    gamma: float = 0.99,
    gae_lambda: float = 0.95,
    clip_range: float = 0.2,
    ent_coef: float = 0.005,
    lambda_vol: float = 0.10,
    lambda_conc: float = 0.001,
    lambda_txn: float = 1.0,
    residual_alpha: float = 0.15,
    residual_mode: str = "momentum",
    rebalance_interval: int = 5,
    momentum_lookback: int = 60,
    momentum_temp: float = 0.2,
    downside_only: bool = True,
    seed: int = 42,
    log_dir: str = "results/ppo_logs",
    checkpoint_dir: str = "results/ppo_checkpoints",
    final_model_path: str = "results/ppo_final_model.zip",
):
    print("=" * 65)
    print("  FINORA PHASE 4: PPO RL TRAINING ON GNN EMBEDDINGS")
    print("=" * 65)
    print(f"Data path:           {data_path}")
    print(f"Embedding dir:       {embedding_dir}")
    print(f"Total timesteps:     {total_timesteps}")
    print(f"Checkpoint freq:     {save_freq}")
    print(f"Residual policy:     alpha={residual_alpha}, mode={residual_mode}, rebalance_interval={rebalance_interval}")
    print(f"Reward weights:      lambda_vol={lambda_vol}, lambda_conc={lambda_conc}, lambda_txn={lambda_txn}, downside_only={downside_only}")
    print(f"Hyperparameters:     lr={learning_rate}, n_steps={n_steps}, batch_size={batch_size}, gamma={gamma}")
    print(f"Seed:                {seed}")

    # Ensure output directories exist
    os.makedirs(checkpoint_dir, exist_ok=True)
    os.makedirs(log_dir, exist_ok=True)
    os.makedirs(os.path.dirname(final_model_path), exist_ok=True)

    # 1. Load market dataset
    full_data_path = os.path.join(BASE_DIR, data_path)
    if not os.path.exists(full_data_path):
        raise FileNotFoundError(f"Training dataset not found: {full_data_path}")
    data = pd.read_parquet(full_data_path)
    print(f"Loaded dataset:      {len(data)} rows, {len(data.index.get_level_values('Date').unique())} unique dates")

    # 2. Instantiate GNN-enhanced environment
    full_emb_dir = os.path.join(BASE_DIR, embedding_dir)
    raw_env = GNNPortfolioEnv(
        data=data,
        embedding_dir=full_emb_dir,
        window=20,
        transaction_cost_bps=10.0,
        initial_cash=1.0,
        return_col="Returns Daily",
        embedding_dim=32,
        lambda_vol=lambda_vol,
        lambda_conc=lambda_conc,
        lambda_txn=lambda_txn,
        residual_alpha=residual_alpha,
        residual_mode=residual_mode,
        rebalance_interval=rebalance_interval,
        momentum_lookback=momentum_lookback,
        momentum_temp=momentum_temp,
        downside_only=downside_only,
        seed=seed,
    )

    # Verify Gymnasium compliance
    check_env(raw_env, warn=True)
    print("Gymnasium environment check: PASSED (No errors)")

    # Wrap in Monitor for episode tracking
    monitor_csv = os.path.join(log_dir, "monitor.csv")
    env = Monitor(raw_env, filename=monitor_csv)

    # 3. Create PPO Agent
    model = PPO(
        policy="MultiInputPolicy",
        env=env,
        learning_rate=learning_rate,
        n_steps=n_steps,
        batch_size=batch_size,
        n_epochs=n_epochs,
        gamma=gamma,
        gae_lambda=gae_lambda,
        clip_range=clip_range,
        ent_coef=ent_coef,
        vf_coef=0.5,
        max_grad_norm=0.5,
        tensorboard_log=None,
        seed=seed,
        verbose=1,
    )

    # 4. Configure Callbacks
    checkpoint_callback = CheckpointCallback(
        save_freq=save_freq,
        save_path=checkpoint_dir,
        name_prefix="ppo_checkpoint",
        save_replay_buffer=False,
        save_vecnormalize=False,
    )

    metrics_csv = os.path.join(log_dir, "training_metrics.csv")
    logger_callback = MetricsLoggerCallback(log_path=metrics_csv)

    callback_list = CallbackList([checkpoint_callback, logger_callback])

    # 5. Train
    print("\n--- Commencing PPO Policy Optimization ---")
    model.learn(
        total_timesteps=total_timesteps,
        callback=callback_list,
        progress_bar=False,
    )

    # 6. Save final models
    final_full_path = os.path.join(BASE_DIR, final_model_path)
    model.save(final_full_path)
    print(f"\n[OK] Final model saved: {final_full_path}")

    # Also save to src/gnn/models/gnn_ppo.zip for backwards compatibility
    legacy_path = os.path.join(BASE_DIR, "src", "gnn", "models", "gnn_ppo.zip")
    os.makedirs(os.path.dirname(legacy_path), exist_ok=True)
    model.save(legacy_path)
    print(f"[OK] Legacy model saved: {legacy_path}")

    print("=" * 65)
    print("  PPO TRAINING COMPLETED SUCCESSFULLY")
    print("=" * 65)
    return model


